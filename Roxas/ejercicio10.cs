//La diferencia entre composición y agregación es:

//La composición se trata de una relación extrecha donde un "algo" no puede existir sin el otro "algo".
////Por ejemplo, un "cuerpo humano" y un "corazón". Un corazón no puede existir sin un cuerpo humano, 
/// por lo tanto, es una relación de composición.
/// 
/// //La agregación se trata de una relación más débil donde un "algo" puede existir sin el otro "algo".
/// //Por ejemplo, un "cuerpo humano" y un "brazalete". Un brazalete puede existir sin un cuerpo humano,
/// //por lo tanto, es una relación de agregación.